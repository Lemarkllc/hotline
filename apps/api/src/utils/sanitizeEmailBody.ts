/**
 * Реальный инцидент 2026-09-23/24: клиенты вставляют изображение (скан/фото
 * размеров) прямо в тело HTML-письма, а не как отдельное вложение. mailparser
 * htmlToText не вырезает такие data-URI — base64-блок картинки (сотни КБ –
 * единицы МБ) остаётся в теле как текст и: (а) раздувает хранимое в БД
 * originalBody мусором, (б) целиком улетает в leadAiService.classify (Yandex AI
 * Studio) без всякого лимита — два таких письма подряд (Л-2026-00642, 1.2 млн
 * символов; Л-2026-00647, 2.5 млн) спалили ~800к токенов за вечер, оба запроса
 * всё равно упали ошибкой. Вырезаем блок целиком и заменяем плейсхолдером —
 * причина отсутствия текста должна быть видна человеку, читающему заявку.
 */
const DATA_URI_RE = /data:[a-z]+\/[a-z0-9.+-]+;base64,[a-zA-Z0-9+/=]+/gi;

export function stripEmbeddedDataUris(text: string): string {
  return text.replace(DATA_URI_RE, "[вложенное изображение убрано из текста письма]");
}

/**
 * Подстраховка на входе в LLM-классификацию (leadAiService.classify) — на случай
 * иного источника раздутия тела, не только data-URI (например, огромная
 * цитируемая переписка). ~20 000 символов — с большим запасом покрывает любое
 * реальное деловое письмо; для классификации релевантности начало письма и так
 * несёт всю нужную информацию.
 */
const MAX_AI_INPUT_CHARS = 20_000;

export function truncateForAi(text: string): string {
  if (text.length <= MAX_AI_INPUT_CHARS) return text;
  return `${text.slice(0, MAX_AI_INPUT_CHARS)}\n\n[письмо обрезано для классификации, исходный объём: ${text.length} символов]`;
}
