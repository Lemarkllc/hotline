/** Фамилия/Имя/Отчество: с большой буквы, дальше строчные (кириллица), можно
 * дефис для двойных фамилий (Петров-Водкин) — без цифр и спецсимволов. 2-3 слова
 * (Отчество не обязательно). Найдено вживую 2026-09-23/24: несколько сотрудников
 * отправили боту "/vpn" вместо имени (случайно тапнули пункт бокового меню в
 * момент, когда бот ждал текстовый ответ) — принято как валидное ФИО, HR
 * одобрил не заметив. Меню на время регистрации отключается отдельно
 * (registration.ts), эта проверка — вторая, независимая линия защиты. */
const NAME_WORD = "[А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?";
const FULL_NAME_PATTERN = new RegExp(`^${NAME_WORD}(?: ${NAME_WORD}){1,2}$`);

export function isValidFullName(text: string): boolean {
  return FULL_NAME_PATTERN.test(text.trim());
}

